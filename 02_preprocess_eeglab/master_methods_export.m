function master_methods_export()
% MASTER_METHODS_EXPORT  Autogenerate paper-ready Methods .md(COBIDAS-compliant)
%
% USAGE
%   master_methods_export();
%
% 從所有 manifest + version stamp + thresholds 自動拼出 paper Methods 段子,
% 含實際跑出來的統計(n_bad 平均、IC removed 平均、epoch retention 等)。
%
% v2.2 ─ 2026/5/27

paths = config_paths();
thr   = config_thresholds();
bands = config_bands();
pipe  = config_pipeline();
stamp = version_stamp();

% 聚合所有 subject 的 manifest 統計
sid_list = subjects();
n_sids = numel(sid_list);
agg = struct('n_bad', [], 'n_ic_removed', [], 'beta_pct', [], 'n_final', [], 'overcorr', []);
for i = 1:n_sids
    mf_path = fullfile(paths.MANIFEST_DIR, [sid_list{i} '.json']);
    if ~exist(mf_path, 'file'); continue; end
    try
        mf = jsondecode(fileread(mf_path));
        agg.n_bad(end+1)        = safefield(mf, {'step1','n_bad'}, NaN);
        agg.n_ic_removed(end+1) = safefield(mf, {'step2b','n_removed'}, NaN);
        agg.beta_pct(end+1)     = safefield(mf, {'step2b','beta_pct_change'}, NaN);
        agg.n_final(end+1)      = safefield(mf, {'step3','n_final'}, NaN);
        agg.overcorr(end+1)     = safefield(mf, {'step2b','overcorr_flag'}, 0);
    catch
    end
end
n_done = numel(agg.n_bad);

% 統計
mean_bad = nanmean(agg.n_bad);
sd_bad   = nanstd(agg.n_bad);
mean_ic  = nanmean(agg.n_ic_removed);
sd_ic    = nanstd(agg.n_ic_removed);
mean_final = nanmean(agg.n_final);
sd_final = nanstd(agg.n_final);
n_overcorr = nansum(agg.overcorr);

% 寫 markdown
out_path = fullfile(paths.METHODS_OUT, 'EEG_methods_v2.2.md');
fid = fopen(out_path, 'w');

fprintf(fid, '# EEG Preprocessing Methods (v2.2)\n\n');
fprintf(fid, '*Autogenerated %s  |  %s*\n\n', stamp.timestamp, stamp.label);

fprintf(fid, '## Acquisition\n\n');
fprintf(fid, 'Resting-state EEG was recorded using a 19-channel system (NeuroGuide), ');
fprintf(fid, 'with electrodes placed according to the international 10–20 system at ');
fprintf(fid, 'Fp1, Fp2, F3, F4, C3, C4, P3, P4, O1, O2, F7, F8, T7, T8, P7, P8, Fz, Cz, Pz. ');
fprintf(fid, 'Sampling rate was 300 Hz. Reference: LinkEars (left/right mastoid average). ');
fprintf(fid, 'Eyes were closed throughout the resting paradigm.\n\n');

fprintf(fid, '## Preprocessing pipeline\n\n');
fprintf(fid, 'EEG data were preprocessed using EEGLAB v%s (Delorme & Makeig, 2004) ', stamp.eeglab_version);
fprintf(fid, 'on MATLAB %s. Pipeline version: %s. ', stamp.matlab_version, pipe.version);
fprintf(fid, 'All scripts, parameters, and random seeds are version-tracked (git hash %s) ', stamp.git_hash);
fprintf(fid, 'for full reproducibility.\n\n');

fprintf(fid, '**Step 1: Filtering & bad channel handling.** ');
fprintf(fid, 'Continuous data were band-pass filtered (%.1f–%g Hz) using a zero-phase ', ...
        thr.bandpass.highpass, thr.bandpass.lowpass);
fprintf(fid, 'FIR filter (`pop_eegfiltnew`). Bad channels were detected using a multi-metric ');
fprintf(fid, 'voting scheme requiring ≥2 of the following to flag: (a) `clean_rawdata` ');
fprintf(fid, 'channel correlation < %.2f, (b) flatline duration > %ds, ', thr.badch.corr_thresh, thr.badch.flatline_sec);
fprintf(fid, '(c) line-noise SNR at 60Hz > %d dB, (d) channel kurtosis robust |z| > %g. ', ...
        thr.badch.line_noise_snr_db, thr.badch.kurtosis_robust_z);
fprintf(fid, 'Flagged channels were interpolated using spherical splines (Perrin et al., 1989). ');
if n_done > 0
    fprintf(fid, 'Across N=%d participants, mean number of interpolated channels = %.2f (SD %.2f).\n\n', ...
            n_done, mean_bad, sd_bad);
end

fprintf(fid, '**Step 2: Line noise removal & ICA.** ');
fprintf(fid, 'Line noise at 60Hz was removed using CleanLine (Mullen, 2012; bandwidth %dHz, tau %d ms). ', ...
        thr.cleanline.bandwidth, thr.cleanline.tau);
fprintf(fid, 'Independent component analysis (ICA) was performed using %s ', thr.ica.algorithm);
if strcmp(thr.ica.algorithm, 'picard')
    fprintf(fid, '(Ablin et al., 2018) ');
end
fprintf(fid, 'with PCA pre-reduction set to the estimated effective data rank. ');
fprintf(fid, 'Per-subject deterministic seeds (hash of subject ID + global seed %d) were used ', pipe.global_seed);
fprintf(fid, 'for reproducibility.\n\n');

fprintf(fid, '**Step 2b: Artifact removal & re-reference.** ');
fprintf(fid, 'Independent components were classified using ICLabel (Pion-Tonachini et al., 2019). ');
fprintf(fid, 'Components with Eye probability ≥ %.2f or Muscle probability ≥ %.2f ', ...
        thr.iclabel.eye_thresh, thr.iclabel.muscle_thresh);
fprintf(fid, 'were auto-flagged and removed in the fully automated run; decisions were stored ');
fprintf(fid, 'as JSON for audit. No manual IC override was applied in this run. ');
fprintf(fid, 'Data were re-referenced to the common average after IC removal. ');
if n_done > 0
    fprintf(fid, 'Mean components removed per subject = %.2f (SD %.2f).\n\n', mean_ic, sd_ic);
end

fprintf(fid, '**Pipeline-level PSD-change QC.** ');
fprintf(fid, 'BRAIN-averaged power spectral density (PSD) was computed before and after the ');
fprintf(fid, 'line-noise removal, IC removal, and average-reference stage. ');
fprintf(fid, 'Per-band percent change was logged. Subjects with |%% change in Beta (%.0f-%.0fHz)| > %d%% ', ...
        bands.primary.Beta(1), bands.primary.Beta(2), thr.overcorr.warn_pct_change);
fprintf(fid, 'were flagged for inspection; this flag is a pipeline-level warning rather than a pure ICA-only estimate. ');
if n_done > 0
    fprintf(fid, '%d / %d (%.1f%%) of subjects exceeded this threshold and were subject to manual inspection.\n\n', ...
            n_overcorr, n_done, 100*n_overcorr/n_done);
end

fprintf(fid, '**Step 3: Epoching & artifact rejection.** ');
fprintf(fid, 'Continuous data were segmented into %g-s non-overlapping epochs. ', thr.epoch.length_sec);
fprintf(fid, 'Three layers of automatic rejection were applied: ');
fprintf(fid, '(A) EEGLAB `pop_autorej` (joint amplitude/kurtosis probability, threshold %d µV, %d SD), ', ...
        thr.epoch.autorej_threshold, thr.epoch.autorej_startprob);
fprintf(fid, '(B) absolute-amplitude hard threshold %d µV, ', thr.epoch.amp_thresh_uv);
fprintf(fid, '(C) sample-to-sample jump > %d µV. ', thr.epoch.jump_thresh_uv);
fprintf(fid, 'Of remaining epochs, %d were randomly sampled (per-subject deterministic seed). ', thr.epoch.target_count);
fprintf(fid, 'Subjects with fewer than %d remaining epochs or rejection rate > %.0f%% ', ...
        thr.epoch.review_min_count, thr.epoch.review_max_reject*100);
fprintf(fid, 'underwent additional manual review. ');
if n_done > 0
    fprintf(fid, 'Mean final epoch count = %.1f (SD %.1f).\n\n', mean_final, sd_final);
end

fprintf(fid, '**Step 4: Power spectral density (PSD).** ');
fprintf(fid, 'PSD was computed per channel per epoch using Welch''s method ');
fprintf(fid, '(Hamming window, %d samples = %gs, no overlap, nfft=%d), ', ...
        thr.psd.win_samples, thr.epoch.length_sec, thr.psd.nfft);
fprintf(fid, 'then averaged across epochs (Bai et al., 2025). ');
fprintf(fid, 'PSD output was retained at %.3f Hz resolution over %.1f–%g Hz.\n\n', ...
        300 / thr.psd.nfft, thr.psd.freq_min, thr.psd.freq_max);

fprintf(fid, '## Relative power computation\n\n');
fprintf(fid, 'Absolute band power was computed by trapezoidal integration of PSD within each band. ');
fprintf(fid, 'Total power for normalization was the sum of five primary, non-overlapping bands: ');
fprintf(fid, 'Delta (%.0f–%.0f Hz), Theta (%.0f–%.0f Hz), Alpha (%.0f–%.0f Hz), Beta (%.0f–%.0f Hz), Gamma (%.0f–%.0f Hz). ', ...
        bands.primary.Delta(1), bands.primary.Delta(2), ...
        bands.primary.Theta(1), bands.primary.Theta(2), ...
        bands.primary.Alpha(1), bands.primary.Alpha(2), ...
        bands.primary.Beta(1),  bands.primary.Beta(2), ...
        bands.primary.Gamma(1), bands.primary.Gamma(2));
fprintf(fid, 'Relative power = (absolute band power) / total × 100%%. ');
fprintf(fid, 'Derived sub-bands (Alpha1/2, Beta1/2/3, HighBeta) were computed as sub-band/total ratios ');
fprintf(fid, 'and do not contribute to the denominator.\n\n');
fprintf(fid, '> **Note on Beta sub-band naming.** ');
fprintf(fid, 'Beta sub-bands in this study are defined as Beta1 = %.0f–%.0f, Beta2 = %.0f–%.0f, Beta3 = %.0f–%.0f Hz. ', ...
        bands.derived.Beta1(1), bands.derived.Beta1(2), ...
        bands.derived.Beta2(1), bands.derived.Beta2(2), ...
        bands.derived.Beta3(1), bands.derived.Beta3(2));
fprintf(fid, 'Note that the high-beta hyperarousal marker reported as "Beta2 = 24-32 Hz" in some literature ');
fprintf(fid, '(e.g., Frontiers 2022) corresponds to Beta3 (24–30 Hz) in our naming convention.\n\n');

fprintf(fid, '## Reproducibility\n\n');
fprintf(fid, 'All preprocessing decisions, parameters, and version stamps are stored as per-subject ');
fprintf(fid, 'JSON manifests and per-step CSV logs. ICA and epoch-sampling random seeds are deterministic ');
fprintf(fid, 'functions of subject ID, ensuring exact reproducibility. The pipeline source code ');
fprintf(fid, 'is version-tracked (git hash %s).\n\n', stamp.git_hash);

fprintf(fid, '## References\n\n');
fprintf(fid, '1. Delorme, A., & Makeig, S. (2004). EEGLAB: an open source toolbox for analysis of single-trial EEG dynamics. *Journal of Neuroscience Methods*, 134(1), 9-21.\n');
fprintf(fid, '2. Pernet, C. R., et al. (2020). Issues and recommendations from the OHBM COBIDAS MEEG committee for reproducible EEG and MEG research. *Nature Neuroscience*, 23, 1473-1483.\n');
fprintf(fid, '3. Pion-Tonachini, L., Kreutz-Delgado, K., & Makeig, S. (2019). ICLabel: An automated electroencephalographic independent component classifier, dataset, and website. *NeuroImage*, 198, 181-197.\n');
fprintf(fid, '4. Ablin, P., Cardoso, J. F., & Gramfort, A. (2018). Faster independent component analysis by preconditioning with Hessian approximations. *IEEE Transactions on Signal Processing*, 66(15), 4040-4049.\n');
fprintf(fid, '5. Perrin, F., Pernier, J., Bertrand, O., & Echallier, J. F. (1989). Spherical splines for scalp potential and current density mapping. *Electroencephalography and Clinical Neurophysiology*, 72(2), 184-187.\n');
fprintf(fid, '6. Mullen, T. (2012). CleanLine EEGLAB plugin. SCCN.\n');
fprintf(fid, '7. Bailey, N. W., et al. (2024). [EEG over-correction warning].\n');
fprintf(fid, '8. Coelli, S., et al. (2024). How do the resting EEG preprocessing states affect the outcomes of postprocessing? *NeuroImage*.\n');
fprintf(fid, '9. Bai, Y., et al. (2025). [SpecParam/FOOOF settings]. *Sleep Medicine*, 129, 45-54.\n');

fclose(fid);

fprintf('Methods exported to: %s\n', out_path);
fprintf('Length: %d lines\n', count_lines(out_path));
end


function v = safefield(s, path, default)
v = default;
try
    for k = 1:numel(path)
        s = s.(path{k});
    end
    v = double(s);
catch
end
end

function n = count_lines(p)
fid = fopen(p, 'r'); n = 0;
while ~feof(fid); fgetl(fid); n = n + 1; end
fclose(fid);
end
